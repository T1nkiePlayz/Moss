#!/usr/bin/env bash
# Regenerates both SDKs from docs/openapi.frozen.json.
#
# Requirements: node 20+ with npm, and python 3.10+ with the venv module. Nothing else is installed globally:
# the TypeScript generator comes from sdk/typescript/package.json (pinned, `npm ci`), and the Python generator is
# installed into a throwaway venv at .tmp/sdk-venv (override with SDK_VENV).
set -euo pipefail

DATAMODEL_CODEGEN_VERSION="0.35.0"

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
spec="$root/docs/openapi.frozen.json"
venv="${SDK_VENV:-$root/.tmp/sdk-venv}"

echo "== TypeScript"
(cd "$root/sdk/typescript" && npm ci --no-audit --no-fund && npm run generate)

echo "== Python"
if [ ! -x "$venv/bin/datamodel-codegen" ]; then
  python3 -m venv "$venv"
  "$venv/bin/pip" install --quiet "datamodel-code-generator==$DATAMODEL_CODEGEN_VERSION"
fi
"$venv/bin/datamodel-codegen" \
  --input "$spec" \
  --input-file-type openapi \
  --output-model-type pydantic_v2.BaseModel \
  --target-python-version 3.10 \
  --use-annotated \
  --disable-timestamp \
  --custom-file-header "# GENERATED FILE. DO NOT EDIT.
# Generated by datamodel-code-generator from docs/openapi.frozen.json (run scripts/gen-sdk.sh)." \
  --output "$root/sdk/python/src/moss_client/models.py"

echo "Done. Review with: git diff --stat sdk/"
